using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

using System.Data;
using System.Diagnostics;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

namespace Net.Code.ADONet.SourceGenerators
{
    public static class SourceGenerationHelper
    {
        internal static SourceCode GenerateExtensionClass(MapperInfo mapper)
        {
            using var builder = new SourceBuilder()
                .WriteLine("// <auto-generated>")
                .WriteUsings("System.Data", "Net.Code.ADONet")
                .WriteLine()
                .WriteLine(mapper is { Namespace: string n } ? $"namespace {n};" : string.Empty)
                .WriteLine($"public static partial class {mapper.Name}Mapper")
                .WriteOpeningBracket();


            // Ordinals are resolved on every call: the same type may be mapped from
            // different queries whose columns come back in a different order, so
            // caching them (e.g. in static fields) would silently map wrong values.
            builder.WriteLine($"public static {mapper.Name} To{mapper.Name}(this IDataRecord record)")
                .WriteOpeningBracket();
            foreach (var p in mapper.Properties)
            {
                builder.WriteLine($"var {OrdinalVariable(p)} = record.GetOrdinal(\"{p.ColumnName.Transform(mapper.NamingConvention)}\");");
            }

            if (mapper.IsRecord)
            {
                builder.Write($"return new {mapper.Name} (");

                builder.Write(string.Join(",", mapper.Properties.Select(GetValueExpression)));

                builder.WriteLine(");");

            }
            else
            {
                builder.WriteLine($"return new {mapper.Name}")
                .WriteOpeningBracket();

                foreach (var p in mapper.Properties)
                {
                    builder.WriteLine($"{p.Name} = {GetValueExpression(p)},");
                }
                builder.WriteClosingBracket(true);
            }

            builder.WriteClosingBracket()
                .WriteClosingBracket();

            return new(builder.ToString(), $"{mapper.Namespace??"global"}.{mapper.Name}MapFromDataRecordExtension.g.cs");

        }

        private static string OrdinalVariable(PropertyInfo property) => $"__ordinal_{property.Name}";

        // Nullable value types (int?) and annotated nullable reference types (string?)
        // map DBNull to null; non-nullable properties read the value directly.
        private static string GetValueExpression(PropertyInfo property)
        {
            var ordinal = OrdinalVariable(property);
            var getValue = $"record.{property.Getter}({ordinal})";
            return property.Nullable
                ? $"record.IsDBNull({ordinal}) ? null : {getValue}"
                : getValue;
        }
    }

    class PropertyInfo(IPropertySymbol symbol)
    {
        public string Name { get; } = symbol.Name;
        public string ColumnName { get; } = symbol.GetAttributes() switch
        {
            [{ AttributeClass.Name: "ColumnAttribute", ConstructorArguments: [{ Value: string n }] }] => n,
            _ => symbol.Name
        };

        public string TypeName { get; } = symbol.Type.ToDisplayString();

        /// <summary>
        /// The IDataRecord getter for this property's type (for Nullable&lt;T&gt;, the getter for T),
        /// or null when the type is not supported.
        /// </summary>
        public string? Getter { get; } = GetGetter(UnwrapNullable(symbol.Type));
        public bool Nullable { get; } = symbol.Type.NullableAnnotation is NullableAnnotation.Annotated;
        public Location? Location { get; } = symbol.Locations.FirstOrDefault();

        private static ITypeSymbol UnwrapNullable(ITypeSymbol type) => type switch
        {
            INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T, TypeArguments: [var underlying] } => underlying,
            _ => type
        };

        // Types without an IDataRecord getter (or that providers report differently) use the
        // extension methods in Net.Code.ADONet.DataRecordGetterExtensions.
        private static string? GetGetter(ITypeSymbol type) => type switch
        {
            { TypeKind: TypeKind.Enum } => $"GetEnum<{type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>",
            IArrayTypeSymbol { Rank: 1, ElementType.SpecialType: SpecialType.System_Byte } => "GetByteArray",
            _ => type.SpecialType switch
            {
                SpecialType.System_Boolean => nameof(IDataRecord.GetBoolean),
                SpecialType.System_Byte => nameof(IDataRecord.GetByte),
                SpecialType.System_Char => nameof(IDataRecord.GetChar),
                SpecialType.System_DateTime => nameof(IDataRecord.GetDateTime),
                SpecialType.System_Decimal => nameof(IDataRecord.GetDecimal),
                SpecialType.System_Double => nameof(IDataRecord.GetDouble),
                SpecialType.System_Single => nameof(IDataRecord.GetFloat),
                SpecialType.System_Int16 => nameof(IDataRecord.GetInt16),
                SpecialType.System_Int32 => nameof(IDataRecord.GetInt32),
                SpecialType.System_Int64 => nameof(IDataRecord.GetInt64),
                SpecialType.System_String => nameof(IDataRecord.GetString),
                _ => (type.ContainingNamespace?.ToDisplayString(), type.MetadataName) switch
                {
                    ("System", "Guid") => nameof(IDataRecord.GetGuid),
                    ("System", "TimeSpan") => "GetTimeSpan",
                    ("System", "DateTimeOffset") => "GetDateTimeOffset",
                    ("System", "DateOnly") => "GetDateOnly",
                    ("System", "TimeOnly") => "GetTimeOnly",
                    _ => null
                }
            }
        };
    }
    internal class MapperInfo(ITypeSymbol type)
    {
        public string? Namespace { get; } = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToString();

        public string Name { get; } = type.Name;

        public bool IsRecord { get; } = type.IsRecord;

        internal NamingConvention NamingConvention { get; } = (
                from a in type.GetAttributes()
                where a.AttributeClass?.Name == "MapFromDataRecordAttribute"
                let columnNamingConvention = (from n in a.NamedArguments
                                              where n.Key == "ColumnNamingConvention"
                                              select n.Value.Value).FirstOrDefault()
                select (NamingConvention?)((int?)columnNamingConvention)
                ).SingleOrDefault() ?? NamingConvention.PascalCase;

        private static IEnumerable<PropertyInfo> GetProperties(ITypeSymbol type)
        {
            if (type.IsRecord && type is INamedTypeSymbol s)
            {
                var properties = type.GetMembers().OfType<IPropertySymbol>().Where(p => p is { SetMethod.IsInitOnly: true,  GetMethod: not null }).ToList();
                var parameters = s.InstanceConstructors.Where(c => c.Parameters.Length == properties.Count).Single().Parameters;
                return (from pa in parameters
                        join pr in properties on pa.Name equals pr.Name
                        select new PropertyInfo(pr)).ToList();
            }
            else
            {
                return type.GetMembers().OfType<IPropertySymbol>().Select(s => new PropertyInfo(s)).ToList();
            }

        }

        public IEnumerable<PropertyInfo> Properties { get; } = GetProperties(type);
    }
}

enum NamingConvention
{
    PascalCase = 0,
    lowercase = 1,
    UPPERCASE = 2
}

internal static class StringExtensions
{
    public static string Transform(this string propertyName, NamingConvention namingConvention)
    {
        return namingConvention switch
        {
            NamingConvention.lowercase => propertyName.ToLowerWithUnderscores(),
            NamingConvention.UPPERCASE => propertyName.ToUpperWithUnderscores(),
            _ => propertyName
        };
    }

    public static string ToUpperWithUnderscores(this string source) => string.Join("_", SplitUpperCase(source).Select(s => s.ToUpperInvariant()));
    public static string ToLowerWithUnderscores(this string source) => string.Join("_", SplitUpperCase(source).Select(s => s.ToLowerInvariant()));
    private static IEnumerable<string> SplitUpperCase(string source)
    {
        var wordStart = 0;
        var letters = source.ToCharArray();
        var previous = char.MinValue;
        for (var i = 1; i < letters.Length; i++)
        {
            if (char.IsUpper(letters[i]) && !char.IsWhiteSpace(previous))
            {
                yield return new string(letters, wordStart, i - wordStart);
                wordStart = i;
            }

            previous = letters[i];
        }

        yield return new string(letters, wordStart, letters.Length - wordStart);
    }
}
